// Serializes schema creation and seeding across concurrent Lambda cold starts.
const SCHEMA_LOCK_ID = 7_310_001;

const CREATED_AT =
  "created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')";

// order_items.product_id has no foreign key on purpose: the API lets admins delete products that
// already appear in orders, as it did on SQLite (where foreign keys were never enforced).
const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'customer')),
    ${CREATED_AT}
  )`,
  `CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    price DOUBLE PRECISION NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    image_url TEXT,
    ${CREATED_AT}
  )`,
  `CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    subtotal DOUBLE PRECISION NOT NULL,
    gst DOUBLE PRECISION NOT NULL,
    total DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
    ${CREATED_AT}
  )`,
  `CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id),
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    price DOUBLE PRECISION NOT NULL
  )`,
  // Gomoku games and cart lines are keyed by owner: 'u:<userId>' for users, 'g:<guestId>' for guests.
  `CREATE TABLE IF NOT EXISTS gomoku_games (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner TEXT NOT NULL,
    board TEXT NOT NULL,
    layout TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('playing', 'won', 'lost', 'draw')),
    claimed INTEGER NOT NULL DEFAULT 0,
    ${CREATED_AT}
  )`,
  // Like order_items, cart_items.product_id has no foreign key so admins can still delete products;
  // cart queries join on products, so lines for deleted products simply drop out.
  `CREATE TABLE IF NOT EXISTS cart_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner TEXT NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    penalty INTEGER NOT NULL DEFAULT 0,
    UNIQUE (owner, product_id, penalty)
  )`,
];


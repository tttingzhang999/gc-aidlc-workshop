function buildProductInsert(products: readonly SeedProduct[]): {
  sql: string;
  params: Param[];
} {
  const rows = products.map((_, row) => {
    const base = row * 5;
    return `($${base + 1}::text, $${base + 2}::text, $${base + 3}::float8, $${base + 4}::int, $${base + 5}::text)`;
  });
  return {
    sql: `INSERT INTO products (name, description, price, stock, image_url) VALUES ${rows.join(', ')}`,
    params: products.flat(),
  };
}

export async function initDb(db: Database): Promise<void> {
  await db.transaction(async (tx) => {
    await tx.query(
      'SELECT 1 AS locked FROM pg_advisory_xact_lock($1::bigint)',
      [SCHEMA_LOCK_ID],
    );
    for (const statement of SCHEMA) {
      await tx.query(statement);
    }

    const [{ count }] = await tx.query<{ count: number }>(
      'SELECT COUNT(*)::int AS count FROM users',
    );
    if (count > 0) return;

    const [adminPassword, customerPassword] = await Promise.all([
      bcrypt.hash('admin123', 10),
      bcrypt.hash('customer123', 10),
    ]);
    await tx.query(
      `INSERT INTO users (email, password, name, role) VALUES
        ($1::text, $2::text, 'Admin User', 'admin'),
        ($3::text, $4::text, 'Customer User', 'customer')`,
      [
        'admin@inventrix.com',
        adminPassword,
        'customer@inventrix.com',
        customerPassword,
      ],
    );

    const { sql, params } = buildProductInsert(SEED_PRODUCTS);
    await tx.query(sql, params);
  });
}
